pub fn is_known(src: &str) -> bool {
    EN.iter().any(|(k, _)| *k == src)
}

pub fn tr(lang: Lang, src: &'static str) -> &'static str {
    match lang {
        Lang::Id => src,
        Lang::En => EN.iter().find(|(k, _)| *k == src).map(|(_, v)| *v).unwrap_or(src),
        Lang::Vi => VI.iter().find(|(k, _)| *k == src).map(|(_, v)| *v).unwrap_or(src),
    }
}

pub fn month_name(lang: Lang, m: u32, id: &'static str) -> &'static str {
    match lang {
        Lang::Id => id,
        Lang::En => {
            const N: [&str; 12] =
                ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
            N.get((m.max(1) - 1) as usize % 12).copied().unwrap_or(id)
        }
        Lang::Vi => {
            const N: [&str; 12] =
                ["Tháng 1", "Tháng 2", "Tháng 3", "Tháng 4", "Tháng 5", "Tháng 6", "Tháng 7", "Tháng 8", "Tháng 9", "Tháng 10", "Tháng 11", "Tháng 12"];
            N.get((m.max(1) - 1) as usize % 12).copied().unwrap_or(id)
        }
    }
}

pub fn month_short(lang: Lang, m: u32) -> &'static str {
    const ID: [&str; 12] = ["Jan", "Feb", "Mar", "Apr", "Mei", "Jun", "Jul", "Agu", "Sep", "Okt", "Nov", "Des"];
    const EN: [&str; 12] = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
    const VI: [&str; 12] = ["Th1", "Th2", "Th3", "Th4", "Th5", "Th6", "Th7", "Th8", "Th9", "Th10", "Th11", "Th12"];
    let i = (m.max(1) - 1) as usize % 12;
    match lang {
        Lang::Id => ID[i],
        Lang::En => EN[i],
        Lang::Vi => VI[i],
    }
}

pub fn weekday_labels(lang: Lang, monday_first: bool, id: [&'static str; 7]) -> [&'static str; 7] {
    match lang {
        Lang::Id => id,
        Lang::En => {
            if monday_first {
                ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
            } else {
                ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"]
            }
        }
        Lang::Vi => {
            if monday_first {
                ["T2", "T3", "T4", "T5", "T6", "T7", "CN"]
            } else {
                ["CN", "T2", "T3", "T4", "T5", "T6", "T7"]
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn indonesian_is_identity_and_english_and_vietnamese_translate() {
        assert_eq!(tr(Lang::Id, "Buka"), "Buka");
        assert_eq!(tr(Lang::En, "Buka"), "Open");
        assert_eq!(tr(Lang::Vi, "Buka"), "Mở");
        assert_eq!(tr(Lang::En, "tidak ada"), "tidak ada");
        assert_eq!(tr(Lang::Vi, "tidak ada"), "tidak ada");
    }

    #[test]
    fn parse_languages() {
        assert_eq!(Lang::parse("vi"), Some(Lang::Vi));
        assert_eq!(Lang::parse("Tiếng Việt"), Some(Lang::Vi));
        assert_eq!(Lang::parse("vietnamese"), Some(Lang::Vi));
        assert_eq!(Lang::Vi.key(), "vi");
    }

    #[test]
    fn no_duplicate_keys_and_vi_matches_en_keys() {
        for (i, (k, _)) in EN.iter().enumerate() {
            assert!(!EN[i + 1..].iter().any(|(k2, _)| k2 == k), "duplikat EN: {k}");
        }
        for (i, (k, _)) in VI.iter().enumerate() {
            assert!(!VI[i + 1..].iter().any(|(k2, _)| k2 == k), "duplikat VI: {k}");
        }
        assert_eq!(VI.len(), EN.len(), "VI and EN key counts must match");
        for (k, _) in EN {
            assert!(VI.iter().any(|(vk, _)| vk == k), "missing VI key: {k}");
        }
    }

    #[test]
    fn calendar_names() {
        assert_eq!(month_name(Lang::En, 11, "November"), "November");
        assert_eq!(month_name(Lang::En, 1, "Januari"), "January");
        assert_eq!(month_name(Lang::Vi, 1, "Januari"), "Tháng 1");
        assert_eq!(month_short(Lang::Vi, 11), "Th11");
        assert_eq!(weekday_labels(Lang::En, true, ["Sen", "Sel", "Rab", "Kam", "Jum", "Sab", "Min"])[0], "Mon");
        assert_eq!(weekday_labels(Lang::Vi, true, ["Sen", "Sel", "Rab", "Kam", "Jum", "Sab", "Min"])[0], "T2");
        assert_eq!(weekday_labels(Lang::Vi, false, ["Sen", "Sel", "Rab", "Kam", "Jum", "Sab", "Min"])[0], "CN");
    }
}
